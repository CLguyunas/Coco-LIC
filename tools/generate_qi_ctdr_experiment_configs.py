#!/usr/bin/env python3
"""Generate reproducible QI-CTDR experiment configs from one dataset config."""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml


def set_common(config):
    config["experiment_profile"] = {"enabled": True}


def set_qi(config, quality, selection):
    config["qi_quality_enable"] = quality
    config["qi_selection_enable"] = selection


def set_detector(config, enabled, mode="continuous_time", threshold=3.0e-3):
    node = config.setdefault("ct_degeneracy", {})
    node.update(
        {
            "enabled": enabled,
            "apply": False,
            "output_csv": True,
            "detector_mode": mode,
            "weak_eigenvalue_ratio": threshold,
        }
    )


def set_recovery(
    config,
    enabled,
    armed=False,
    policy="weak_subspace",
    seed=42,
    budget=64,
):
    node = config.setdefault("ct_visual_recovery", {})
    node.update(
        {
            "enabled": enabled,
            "apply_to_estimator": armed,
            "output_csv": True,
            "selection_policy": policy,
            "random_seed": seed,
            "max_additional_visual_observations": budget,
        }
    )


def make_variant(base, qi_quality, qi_selection, detector, recovery):
    config = copy.deepcopy(base)
    set_common(config)
    set_qi(config, qi_quality, qi_selection)
    set_detector(config, **detector)
    set_recovery(config, **recovery)
    return config


def variants(base, random_seeds):
    detector_off = {"enabled": False}
    recovery_off = {"enabled": False}
    output = {
        "E1_original": make_variant(
            base, False, False, detector_off, recovery_off
        ),
        "E2_q": make_variant(
            base, True, False, detector_off, recovery_off
        ),
        "E2_i": make_variant(
            base, False, True, detector_off, recovery_off
        ),
        "E1_E2_qi": make_variant(
            base, True, True, detector_off, recovery_off
        ),
        "E3_ct_spline": make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "continuous_time"},
            recovery_off,
        ),
        "E3_scan_6d": make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "scan_6d"},
            recovery_off,
        ),
        "E4_shadow": make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "continuous_time"},
            {"enabled": True, "armed": False, "policy": "weak_subspace"},
        ),
        "E1_E4_ctdr": make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "continuous_time"},
            {"enabled": True, "armed": True, "policy": "weak_subspace"},
        ),
        "E4_global_d": make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "continuous_time"},
            {"enabled": True, "armed": True, "policy": "global_d"},
        ),
    }
    for seed in random_seeds:
        output[f"E4_random_seed_{seed}"] = make_variant(
            base,
            True,
            True,
            {"enabled": True, "mode": "continuous_time"},
            {
                "enabled": True,
                "armed": True,
                "policy": "random",
                "seed": seed,
            },
        )
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument(
        "--random-seeds", default="0,1,2,3,4",
        help="comma-separated integer seeds",
    )
    args = parser.parse_args()
    try:
        with args.base.open("r", encoding="utf-8") as stream:
            base = yaml.safe_load(stream)
        if not isinstance(base, dict):
            raise ValueError("base YAML root must be a mapping")
        seeds = [
            int(value.strip())
            for value in args.random_seeds.split(",")
            if value.strip()
        ]
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, config in variants(base, seeds).items():
            output_path = args.output_dir / f"{name}.yaml"
            with output_path.open("w", encoding="utf-8") as stream:
                stream.write(
                    "# Generated by generate_qi_ctdr_experiment_configs.py\n"
                )
                stream.write(f"# Base: {args.base}\n")
                yaml.safe_dump(
                    config,
                    stream,
                    sort_keys=False,
                    default_flow_style=False,
                    allow_unicode=True,
                )
            print(output_path)
        return 0
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(f"config generation error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
